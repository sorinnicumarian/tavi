"""
Runner and callable API for the LTL-template generation stage.

This module translates mission-specific plain-English safety rules into
parametric LTL-template JSON objects.
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List

from dotenv import load_dotenv

from .ltl_template_generation_config import (
    LTLTemplateGenerationConfig,
    save_json,
)
from .ltl_template_translator_agent import LTLTemplateTranslatorAgent


JsonDict = Dict[str, Any]

load_dotenv()


def _rule_generation_root() -> Path:
    """
    Returns tavi/rule_generation regardless of current working directory.

    Current file lives at:
      tavi/rule_generation/src/ltl/main_ltl_template_generation.py
    """
    return Path(__file__).resolve().parents[2]


def generate_ltl_templates_for_rules(
    *,
    plain_english_rules_path: Path | str,
    output_dir: Path | str,
    model: str = "gemini-2.5-pro",
    temperature: float = 0.2,
    max_output_tokens: int = 8192,
    thinking_budget: int = 1024,
) -> Path:
    """
    Translate one task's generated plain-English rules into LTL templates.

    Parameters
    ----------
    plain_english_rules_path:
        Path to the mission-specific plain_english_rules.json generated by the
        online English rule generator.

    output_dir:
        Directory where LTL outputs should be saved.
    """
    root = _rule_generation_root()

    plain_english_rules_path = Path(plain_english_rules_path).resolve()
    output_dir = Path(output_dir).resolve()

    if not plain_english_rules_path.exists():
        raise FileNotFoundError(
            f"Plain-English rules file not found: {plain_english_rules_path}"
        )

    config = LTLTemplateGenerationConfig.from_project_root(
        project_root=root,
        input_rules_path=plain_english_rules_path,
        output_dir=output_dir,
    )

    rendered_prompts = config.render_all_prompts()

    agent = LTLTemplateTranslatorAgent(
        model=model,
        temperature=temperature,
        max_output_tokens=max_output_tokens,
        thinking_budget=thinking_budget,
        max_revision_rounds=0,
    )

    accepted: List[JsonDict] = []

    print(f"Loaded {len(rendered_prompts)} plain-English rule(s).")
    print("Starting LTL-template generation...")

    for index, item in enumerate(rendered_prompts, start=1):
        rule_id = item["rule_id"]
        source_rule = item["rule"]
        prompt = item["prompt"]

        print(f"\n[{index}/{len(rendered_prompts)}] Translating {rule_id}...")

        generated = None

        try:
            generated = agent.translate_rule(prompt)
            print(f"{rule_id}: accepted")
            accepted.append(generated)

        except Exception as exc:
            print(f"{rule_id}: failed with exception: {exc}")

    save_json(config.accepted_templates_path, accepted)
    final_templates_path = root / "outputs" / "rules_ltl_templates.json"
    save_json(final_templates_path, accepted)

    print("\nDone.")
    print(f"Saved templates to: {config.accepted_templates_path}")
    print(f"Saved final templates to: {final_templates_path}")

    return output_dir
